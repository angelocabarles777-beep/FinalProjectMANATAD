    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       int row = tableClients.getSelectedRow();
       
        if (row < 0) {
            JOptionPane.showMessageDialog(this,
                    "No row is selected! Please select one row",
                    "select row", 
                    JOptionPane.ERROR_MESSAGE);
        } else  {
             DefaultTableModel model = (DefaultTableModel) tableClients.getModel();
             model.removeRow(row);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void formWindowClosing(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowClosing
         DefaultTableModel model = (DefaultTableModel) tableClients.getModel();
         Vector<Vector> tableData = model.getDataVector();
         
         //saving of objectin a file
         try {
             FileOutputStream file = new FileOutputStream("file.bin");
             ObjectOutputStream output = new ObjectOutputStream(file);

             //Method for serialization of object
             
             output.writeObject(tableData);
             
             output.close();
             file.close();
         }  catch (Exception ex) {
             ex.printStackTrace();
         }
    }//GEN-LAST:event_formWindowClosing

    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
          try {
             FileInputStream file = new FileInputStream("file.bin");
             ObjectInputStream input = new ObjectInputStream(file);
             
              Vector<Vector> tableData = (Vector<Vector>) input.readObject();
              
             input.close();
             file.close();
             
             DefaultTableModel model = (DefaultTableModel) tableClients.getModel();
              for (int i = 0; i < tableData.size(); i++) {
                  Vector row = tableData.get(i);
                  model.addRow(new Object[] {row.get(0), row.get(1), row.get(2), row.get(3)});
             }                 
          } catch (Exception ex) {
             ex.printStackTrace();
          }
    }//GEN-LAST:event_formWindowOpened

    private void btnSortNameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSortNameActionPerformed
     DefaultTableModel model =
            (DefaultTableModel) tableClients.getModel();

    TableRowSorter<DefaultTableModel> sorter =
            new TableRowSorter<>(model);

    tableClients.setRowSorter(sorter);

    // Sort by Name (column index 0), ascending A to Z
    sorter.setSortKeys(java.util.Collections.singletonList(
            new RowSorter.SortKey(0, javax.swing.SortOrder.ASCENDING)
    ));

    sorter.sort();

    }//GEN-LAST:event_btnSortNameActionPerformed

